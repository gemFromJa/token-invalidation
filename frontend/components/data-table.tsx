const toggleSort = (
  sortArray: SortingState,
  columnId: string,
  direction: "asc" | "desc"
) => {
  const existingSortIndex = sortArray.findIndex((sort) => sort.id === columnId);

  if (existingSortIndex !== -1) {
    // If the column is already sorted, toggle the direction
    const existingSortDirection = sortArray[existingSortIndex];
    const newDirection = existingSortDirection.desc ? "asc" : "desc";
    const newSortArray = [...sortArray];
    newSortArray[existingSortIndex] = {
      id: columnId,
      desc: newDirection === "desc",
    };
    return newSortArray;
  } else {
    // If the column is not sorted, add it to the sort array
    return [{ id: columnId, desc: direction === "desc" }];
  }
};

